// Regenerates extension/lib/* from the shared sources so the extension reuses
// exactly the same fetch config and renderer as the console script / web page.
//   node extension/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const between = (txt, a, b) => { const i = txt.indexOf(a), j = txt.indexOf(b); if (i < 0 || j < 0) throw new Error('marker missing: ' + a); return txt.slice(i + a.length, j); };

const html = fs.readFileSync(path.join(root, 'web/index.html'), 'utf8');
const engine = between(html, '// ==XAM-ENGINE-START== (shared with extension/build.mjs)', '// ==XAM-ENGINE-END==');
fs.writeFileSync(path.join(here, 'lib/mosaic.js'),
  `// GENERATED from web/index.html by extension/build.mjs — do not edit.\n(() => {\n'use strict';\nif (self.XAM) return;\nconst $ = (id) => document.getElementById(id);\n${engine}\n})();\n`);

const fetchSrc = fs.readFileSync(path.join(root, 'fetch/fetch-followers.js'), 'utf8');
const cfg = between(fetchSrc, '// ==XAM-CONFIG-START==', '// ==XAM-CONFIG-END==');
fs.writeFileSync(path.join(here, 'lib/x-config.js'),
  `// GENERATED from fetch/fetch-followers.js by extension/build.mjs — do not edit.\n(() => {\n${cfg}\nself.XAM_CONFIG = CONFIG;\n})();\n`);
// shared i18n dictionary
fs.copyFileSync(path.join(root, 'web/i18n.js'), path.join(here, 'lib/i18n.js'));
// bundled open-licensed fonts (local only; no remote font loading)
fs.mkdirSync(path.join(here, 'fonts'), { recursive: true });
for (const f of fs.readdirSync(path.join(root, 'web/fonts'))) fs.copyFileSync(path.join(root, 'web/fonts', f), path.join(here, 'fonts', f));
// fonts as bytes for the in-page overlay (the x.com page can't load extension files without web_accessible_resources)
const fdata = {};
for (const f of fs.readdirSync(path.join(root, 'web/fonts')).filter((f) => f.endsWith('.woff')))
  fdata[f] = 'data:font/woff;base64,' + fs.readFileSync(path.join(root, 'web/fonts', f)).toString('base64');
fs.writeFileSync(path.join(here, 'lib/fonts-data.js'), `// GENERATED by extension/build.mjs — bundled OFL fonts (see fonts/OFL-*.txt).\nself.XAM_FONT_DATA = ${JSON.stringify(fdata)};\n`);
console.log('built lib/mosaic.js, lib/x-config.js, lib/i18n.js, lib/fonts-data.js, fonts/');
